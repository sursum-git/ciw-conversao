   function lookup_situacao_container(&$situacao_container) 
   {
      $conteudo = "" ; 
      if ($situacao_container == "1")
      { 
          $conteudo = "Aberto";
      } 
      if ($situacao_container == "2")
      { 
          $conteudo = "Suspenso";
      } 
      if ($situacao_container == "3")
      { 
          $conteudo = "Fechado";
      } 
      if (!empty($conteudo)) 
      { 
          $situacao_container = $conteudo; 
      } 
   }  
